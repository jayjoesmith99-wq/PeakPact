const storageKey = '@peakpact/language';

const supportedLanguageEntries: SupportedLanguageOption[] = [
  { code: 'en', label: 'EN' },
  { code: 'es', label: 'ES' },
  { code: 'fr', label: 'FR' },
  { code: 'de', label: 'DE' },
  { code: 'pt', label: 'PT' },
  { code: 'ja', label: 'JA' },
  { code: 'zh', label: 'ZH' },
];

export type TranslationKey = keyof typeof resources.en.translation;

function normalizeLanguage(value?: string | null): SupportedLanguage {
  if (!value) {
    return 'en';
  }
  const lowered = value.toLowerCase();
  if (lowered.startsWith('es')) return 'es';
  if (lowered.startsWith('fr')) return 'fr';
  if (lowered.startsWith('de')) return 'de';
  if (lowered.startsWith('pt')) return 'pt';
  if (lowered.startsWith('ja')) return 'ja';
  if (lowered.startsWith('zh')) return 'zh';
  return 'en';
}

export function resolveLanguage(value?: string | null): SupportedLanguage {
  const candidate = value?.trim();
  if (candidate && candidate in resources) {
    return candidate as SupportedLanguage;
  }
  return normalizeLanguage(candidate);
}

export async function getStoredLanguage(): Promise<SupportedLanguage> {
  try {
    const storage = await getAsyncStorage();
    const stored = await storage?.getItem(storageKey);
    if (stored) {
      return resolveLanguage(stored);
    }
  } catch {
    // ignore storage errors and fall back to device language
  }

  try {
    const localization = await getLocalization();
    const locales = localization?.getLocales?.();
    const deviceLocale = locales?.[0]?.languageCode ?? localization?.locale ?? 'en';
    return resolveLanguage(deviceLocale);
  } catch {
    return 'en';
  }
}

export async function setStoredLanguage(language: SupportedLanguage) {
  const storage = await getAsyncStorage();
  await storage?.setItem(storageKey, language);
  await i18next.changeLanguage(language);
}

export function getSupportedLanguages(): SupportedLanguageOption[] {
  return supportedLanguageEntries;
}

export function getLocalizedText(key: TranslationKey | string, language?: SupportedLanguage | string) {
  const resolvedLanguage = resolveLanguage(language ?? i18next.language ?? 'en');
  const translation = resources[resolvedLanguage]?.translation?.[key as TranslationKey];
  return translation ?? key;
}

export const i18n = i18next.createInstance();

void i18n.use(initReactI18next).init({
  resources: resources as never,
  lng: 'en',
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
});

export async function initializeI18n() {
  const detected = await getStoredLanguage();
  await i18n.changeLanguage(detected);
  return detected;
}

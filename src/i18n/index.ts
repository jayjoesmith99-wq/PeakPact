import i18n from "i18next";
import AsyncStorage from "@react-native-async-storage/async-storage";

const LANGUAGE_KEY = "@peakpact/stored-language";

export async function initializeI18n(): Promise<void> {
  if (i18n.isInitialized) return;

  try {
    const localeResources = Object.fromEntries(
      Object.entries(resources).map(([lng, value]) => [lng, { translation: value.translation }]),
    ) as Record<string, { translation: Record<string, string> }>;

    await i18n.init({
      compatibilityJSON: "v4",
      fallbackLng: "en",
      supportedLngs: Object.keys(localeResources),
      resources: localeResources,
      interpolation: { escapeValue: false },
    });
  } catch (e) {
    console.warn("i18n init warning:", e);
  }
}

